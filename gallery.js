        function openLightbox(index) {
            activeImageIndex = index;
            updateLightboxContent();
            
            const lightbox = document.getElementById("lightbox");
            lightbox.classList.remove("hidden");
        }

        function closeLightbox() {
            document.getElementById("lightbox").classList.add("hidden");
        }

        function navigateLightbox(dir) {
            const images = galleryData[activeCategoryIndex].images;
            activeImageIndex += dir;
            
            if (activeImageIndex < 0) {
                activeImageIndex = images.length - 1;
            } else if (activeImageIndex >= images.length) {
                activeImageIndex = 0;
            }
            updateLightboxContent();
        }

        function updateLightboxContent() {
            const currentImg = galleryData[activeCategoryIndex].images[activeImageIndex];
            
            document.getElementById("lightbox-img").src = currentImg.url;
            document.getElementById("lightbox-title").innerText = currentImg.title;
            document.getElementById("lightbox-desc").innerText = currentImg.subtitle;
        }

