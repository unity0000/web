        // -------------------------
        // 5. CANVAS PARTICLE SIMULATOR
        // -------------------------
        const canvas = document.getElementById("particleCanvas");
        const ctx = canvas.getContext("2d");

        let particlesArray = [];
        let mouse = {
            x: null,
            y: null,
            radius: 120
        };

        function resizeCanvas() {
            canvas.width = window.innerWidth;
            canvas.height = Math.max(document.body.scrollHeight, window.innerHeight);
        }
        window.addEventListener('resize', () => {
            resizeCanvas();
            initParticles();
        });
        resizeCanvas();

        window.addEventListener('mousemove', (e) => {
            mouse.x = e.pageX;
            mouse.y = e.pageY;
        });

        window.addEventListener('mouseleave', () => {
            mouse.x = null;
            mouse.y = null;
        });

        class Particle {
            constructor(x, y, directionX, directionY, size, color) {
                this.x = x;
                this.y = y;
                this.directionX = directionX;
                this.directionY = directionY;
                this.size = size;
                this.color = color;
                this.baseSize = size;
            }

            draw() {
                ctx.beginPath();
                ctx.arc(this.x, this.y, this.size, 0, Math.PI * 2, false);
                ctx.fillStyle = this.color;
                ctx.fill();
            }

            update() {
                if (this.x > canvas.width || this.x < 0) this.directionX = -this.directionX;
                if (this.y > canvas.height || this.y < 0) this.directionY = -this.directionY;

                if (mouse.x !== null && mouse.y !== null) {
                    let dx = mouse.x - this.x;
                    let dy = mouse.y - this.y;
                    let distance = Math.hypot(dx, dy);

                    if (distance < mouse.radius) {
                        const force = (mouse.radius - distance) / mouse.radius;
                        this.x -= dx / distance * force * 3;
                        this.y -= dy / distance * force * 3;
                        this.size = this.baseSize * 1.5;
                    } else {
                        if (this.size > this.baseSize) this.size -= 0.1;
                    }
                }

                this.x += this.directionX;
                this.y += this.directionY;
                this.draw();
            }
        }

        function initParticles() {
            particlesArray = [];
            let numberOfParticles = (canvas.width * canvas.height) / 14000;
            numberOfParticles = Math.min(numberOfParticles, 150);

            for (let i = 0; i < numberOfParticles; i++) {
                let size = Math.random() * 2.5 + 1;
                let x = Math.random() * canvas.width;
                let y = Math.random() * canvas.height;
                let directionX = (Math.random() * 0.4) - 0.2;
                let directionY = (Math.random() * 0.4) - 0.2;
                
                let colors = ['rgba(6, 182, 212, 0.2)', 'rgba(99, 102, 241, 0.15)', 'rgba(139, 92, 246, 0.15)'];
                let color = colors[Math.floor(Math.random() * colors.length)];

                particlesArray.push(new Particle(x, y, directionX, directionY, size, color));
            }
        }

        function animateEngine() {
            ctx.clearRect(0, 0, canvas.width, canvas.height);
            for (let i = 0; i < particlesArray.length; i++) {
                particlesArray[i].update();
            }
            requestAnimationFrame(animateEngine);
        }

        initParticles();
        animateEngine();
