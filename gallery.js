        function renderGallery() {
            const currentCat = galleryData[activeCategoryIndex];
            
            // Render Headings & Info
            document.getElementById("active-category-title").innerText = currentCat.title;
            document.getElementById("category-description").innerText = currentCat.desc;
            document.getElementById("slider-indicator").innerText = `PANEL ${activeCategoryIndex + 1} / ${galleryData.length}`;

            const grid = document.getElementById("gallery-grid");
            
            // Fade-out transition
            grid.classList.add("opacity-0");
            
            setTimeout(() => {
                grid.innerHTML = "";
                
                // Populating Row-Column Panels
                currentCat.images.forEach((img, index) => {
                    const card = document.createElement("div");
                    card.className = "gallery-card group relative overflow-hidden rounded-2xl border border-slate-800/80 bg-slate-900/40 aspect-video cursor-pointer";
                    card.setAttribute("onclick", `openLightbox(${index})`);
                    
                    card.innerHTML = `
                        <img src="${img.url}" class="w-full h-full object-cover transition-transform duration-700 group-hover:scale-110" alt="${img.title}">
                        <div class="absolute inset-0 bg-gradient-to-t from-slate-950 via-slate-950/20 to-transparent opacity-0 group-hover:opacity-100 transition-opacity duration-300 flex items-end p-6">
                            <div>
                                <span class="text-xs font-pixel text-cyan-400 uppercase tracking-widest">${img.subtitle}</span>
                                <h4 class="text-lg font-bold text-white mt-1">${img.title}</h4>
                            </div>
                        </div>
                    `;
                    grid.appendChild(card);
                    
                    // Trigger entry transition delay per card
                    setTimeout(() => {
                        card.classList.add("show");
                    }, index * 100);
                });

                // Fade back in smoothly
                grid.classList.remove("opacity-0");
            }, 300);
        }

